-- Durable Windows-authoritative catalog synchronization.
--
-- Live mode is deliberately unavailable until an immutable SQLite snapshot
-- has been compared with zero remaining catalog differences and registered as
-- the baseline for one Windows source instance.
CREATE TABLE catalog_sync_settings (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    mode TEXT NOT NULL DEFAULT 'manual-snap'
        CHECK (mode IN ('live', 'manual-snap', 'off')),
    source_root TEXT NOT NULL DEFAULT '',
    target_root TEXT NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO catalog_sync_settings(singleton)
VALUES(TRUE)
ON CONFLICT(singleton) DO NOTHING;

CREATE TABLE catalog_sync_sources (
    source_instance_id TEXT PRIMARY KEY,
    source_label TEXT NOT NULL DEFAULT '',
    baseline_state TEXT NOT NULL DEFAULT 'pending'
        CHECK (baseline_state IN ('pending', 'ready', 'drifted')),
    baseline_fingerprint TEXT NOT NULL DEFAULT '',
    baseline_revision BIGINT NOT NULL DEFAULT 0,
    last_received_revision BIGINT NOT NULL DEFAULT 0,
    last_applied_revision BIGINT NOT NULL DEFAULT 0,
    source_root TEXT NOT NULL DEFAULT '',
    target_root TEXT NOT NULL DEFAULT '',
    protocol_version INTEGER NOT NULL DEFAULT 1,
    last_integrity_digest TEXT NOT NULL DEFAULT '',
    last_integrity_at TIMESTAMPTZ,
    last_error TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE catalog_sync_events (
    source_instance_id TEXT NOT NULL REFERENCES catalog_sync_sources(source_instance_id),
    local_revision BIGINT NOT NULL,
    event_id TEXT NOT NULL,
    entity_table TEXT NOT NULL CHECK (entity_table IN ('artists', 'albums', 'tracks')),
    entity_key TEXT NOT NULL,
    operation TEXT NOT NULL CHECK (operation IN ('upsert', 'delete')),
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    payload_digest TEXT NOT NULL,
    observed_artwork_revision BIGINT NOT NULL DEFAULT 0,
    protocol_version INTEGER NOT NULL DEFAULT 1,
    status TEXT NOT NULL DEFAULT 'received'
        CHECK (status IN ('received', 'applied', 'noop', 'blocked', 'failed')),
    error TEXT NOT NULL DEFAULT '',
    source_created_at TEXT NOT NULL DEFAULT '',
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    applied_at TIMESTAMPTZ,
    PRIMARY KEY(source_instance_id, local_revision),
    UNIQUE(source_instance_id, event_id)
);

CREATE INDEX catalog_sync_events_pending
    ON catalog_sync_events(source_instance_id, status, local_revision);

CREATE TABLE catalog_sync_entity_state (
    source_instance_id TEXT NOT NULL REFERENCES catalog_sync_sources(source_instance_id),
    entity_table TEXT NOT NULL,
    entity_key TEXT NOT NULL,
    last_revision BIGINT NOT NULL,
    payload_digest TEXT NOT NULL,
    operation TEXT NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(source_instance_id, entity_table, entity_key)
);

CREATE TABLE catalog_sync_integrity_checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_instance_id TEXT NOT NULL REFERENCES catalog_sync_sources(source_instance_id),
    source_revision BIGINT NOT NULL,
    source_counts JSONB NOT NULL DEFAULT '{}'::jsonb,
    target_counts JSONB NOT NULL DEFAULT '{}'::jsonb,
    source_digest TEXT NOT NULL,
    target_digest TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('match', 'drifted', 'failed')),
    error TEXT NOT NULL DEFAULT '',
    checked_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE catalog_sync_events IS
    'Immutable SQLite catalog events; PostgreSQL consumption is ordered and idempotent per source revision.';
