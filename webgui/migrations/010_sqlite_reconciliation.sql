-- Incremental, reviewable SQLite-to-PostgreSQL reconciliation history.
CREATE TABLE salite_diff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL,
    last_run_id TEXT NOT NULL,
    source_fingerprint TEXT NOT NULL,
    source_label TEXT NOT NULL,
    entity_table TEXT NOT NULL,
    entity_key TEXT NOT NULL,
    difference_type TEXT NOT NULL CHECK (
        difference_type IN ('insert', 'update', 'derived')
    ),
    old_digest TEXT NOT NULL DEFAULT '',
    new_digest TEXT NOT NULL,
    source_value JSONB NOT NULL DEFAULT '{}'::jsonb,
    target_value JSONB NOT NULL DEFAULT '{}'::jsonb,
    resolution TEXT NOT NULL CHECK (
        resolution IN ('safe', 'conflict', 'derived', 'applied', 'skipped')
    ),
    application_outcome TEXT NOT NULL DEFAULT 'pending',
    error TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    applied_at TIMESTAMPTZ,
    UNIQUE (
        source_fingerprint,
        entity_table,
        entity_key,
        difference_type,
        old_digest,
        new_digest
    )
);

CREATE INDEX salite_diff_run_order
    ON salite_diff(last_run_id, id);
CREATE INDEX salite_diff_review
    ON salite_diff(resolution, application_outcome, id DESC);

CREATE TABLE sqlite_reconciliation_runs (
    run_id TEXT PRIMARY KEY,
    source_fingerprint TEXT NOT NULL,
    source_label TEXT NOT NULL,
    trigger TEXT NOT NULL,
    status TEXT NOT NULL,
    differences INTEGER NOT NULL DEFAULT 0,
    safe_differences INTEGER NOT NULL DEFAULT 0,
    conflicts INTEGER NOT NULL DEFAULT 0,
    applied INTEGER NOT NULL DEFAULT 0,
    failures INTEGER NOT NULL DEFAULT 0,
    error TEXT NOT NULL DEFAULT '',
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ
);

CREATE INDEX sqlite_reconciliation_runs_recent
    ON sqlite_reconciliation_runs(started_at DESC);

CREATE TABLE sqlite_reconciliation_settings (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    auto_apply_safe BOOLEAN NOT NULL DEFAULT FALSE,
    interval_minutes INTEGER NOT NULL DEFAULT 1440 CHECK (interval_minutes BETWEEN 15 AND 10080),
    source_path TEXT NOT NULL DEFAULT '',
    source_root TEXT NOT NULL DEFAULT '',
    target_root TEXT NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_run_at TIMESTAMPTZ,
    next_run_at TIMESTAMPTZ
);

INSERT INTO sqlite_reconciliation_settings(singleton)
VALUES(TRUE)
ON CONFLICT(singleton) DO NOTHING;
