CREATE TABLE web_jobs (
 id TEXT PRIMARY KEY,
 kind TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'staged' CHECK (state IN ('staged','queued','running','waiting','paused','done','failed','cancelled')),
 payload JSONB NOT NULL,
 progress JSONB NOT NULL DEFAULT '{}'::jsonb,
 decision JSONB,
 result JSONB,
 error TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX web_jobs_pending ON web_jobs(state,created_at);
CREATE TABLE web_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 action TEXT NOT NULL,
 subject TEXT NOT NULL,
 details JSONB NOT NULL DEFAULT '{}'::jsonb,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
